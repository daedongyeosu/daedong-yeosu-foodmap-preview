import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('rc6-fixes.js','utf8');
const extract=(start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
const code=extract('function rc6CampaignStoreById(id){','function rc6PrepareCampaignStores(){')+extract('function rc6HeroCampaignForEntryStoreId(id){','function rc6CampaignMenuImage(value){');
const canonical={id:'canonical',mergedStoreIds:['legacy'],name:'same verified branch'};
const campaign={storeId:'legacy',slides:[{storeId:'legacy',image:'held-photo.jpg'}]};
const context=vm.createContext({window:{daedongDataApi:{isCustomerHiddenStoreId:id=>id==='hidden'}},stores:[canonical,{id:'other-branch'}],rc6CampaignVirtualStores:new Map(),rc6HeroCampaigns:{campaigns:{legacy:campaign,hidden:{storeId:'hidden'}}},URLSearchParams,location:{search:'?hero=legacy'}});
vm.runInContext(code,context);
assert.equal(context.rc6CampaignStoreById('legacy'),canonical,'Old slide taps must resolve to canonical detail');
assert.equal(context.rc6HeroCampaignForEntryStoreId('legacy'),campaign,'Printed QR keeps its campaign');
assert.equal(context.rc6HeroCampaignForEntryStoreId('canonical'),campaign,'New canonical links inherit the old campaign');
assert.equal(context.rc6RequestedHeroCampaign().store,canonical);
assert.equal(context.rc6RequestedHeroCampaign().campaign.slides[0].image,'held-photo.jpg');
assert.equal(context.rc6HeroCampaignForEntryStoreId('other-branch'),null);
assert.equal(context.rc6HeroCampaignForEntryStoreId('hidden'),null);
const own={storeId:'canonical',slides:[]};context.rc6HeroCampaigns.campaigns.canonical=own;
assert.equal(context.rc6HeroCampaignForEntryStoreId('canonical'),own,'Explicit canonical campaign wins');
assert.equal(context.rc6HeroCampaignForEntryStoreId('legacy'),campaign,'Legacy QR remains stable');
canonical.mergedStoreIds.push('hidden');assert.equal(context.rc6CampaignStoreById('hidden'),undefined);
console.log('Merged-store campaign QR, slide resolution, canonical preference and hidden-store guards passed');
