import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
const context=createRequire(import.meta.url)('./store-context.js');
const draft={previewOnly:true,storeId:'store-a',address:'전남 여수시 테스트길',subsidy:1000,minimumOrder:5000};
assert.equal(context.matchingDraft(draft,'store-b'),null);
assert.equal(context.matchingDraft({...draft,previewOnly:false},'store-a'),null);
assert.equal(context.matchingDraft(draft,'store-a'),draft);
assert.equal(context.metadata(null).address,undefined);
assert.equal(context.metadata(draft).subsidy,1000);
assert.equal(context.metadata({...draft,subsidy:-1}).subsidy,0);
assert.equal(context.id('__proto__'),'');
const onboarding=fs.readFileSync('store-partner/app.js','utf8');
assert.ok(onboarding.includes('`preview-${crypto.randomUUID()}`'));
assert.ok(!onboarding.includes("storeId:String(previous?.storeId||'demo-yeosu-store')"));
const customer=fs.readFileSync('online-store/app.js','utf8');
assert.ok(customer.includes('if(catalogMode&&(!serverCatalogActive||!store.address))'));
assert.ok(customer.includes('if(catalogMode&&!document.querySelector(\'#orderReviewPanel\').hidden)return'));
